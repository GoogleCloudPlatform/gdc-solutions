# Renders DRY Kustomize overlays under overlays/ into the WET plain-KRM bundles
# under fleet-package/environments/ consumed by Google Cloud Config Delivery.
# Pass a single variant name (store-1, store-2, or central-aggregator), or omit
# arguments to render all three variants.

set -o errexit
set -o nounset
set -o pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SOLUTION_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
REPO_ROOT="$(git -C "${SCRIPT_DIR}" rev-parse --show-toplevel 2> /dev/null || (cd "${SOLUTION_ROOT}/../../.." && pwd))"

if [[ $# -gt 0 ]]; then
  VARIANTS=("$@")
else
  VARIANTS=("store-1" "store-2" "central-aggregator")
fi

render_variant() {
  local variant="$1"
  local overlay_dir="${SOLUTION_ROOT}/overlays/${variant}"
  local output_dir="${SCRIPT_DIR}/environments/${variant}"
  local output_file="${output_dir}/manifests.yaml"
  local tmp_file

  mkdir -p "${output_dir}"
  tmp_file="$(mktemp --suffix=.yaml)"
  trap 'rm -f "${tmp_file:-}"' RETURN

  {
    cat << 'EOF'
# Copyright 2026 Google LLC
#
# Licensed under the Apache License, Version 2.0 (the "License");
# you may not use this file except in compliance with the License.
# You may obtain a copy of the License at
#
#     http://www.apache.org/licenses/LICENSE-2.0
#
# Unless required by applicable law or agreed to in writing, software
# distributed under the License is distributed on an "AS IS" BASIS,
# WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
# See the License for the specific language governing permissions and
# limitations under the License.

# Generated by render.sh from overlays/. Do not edit by hand.
EOF
    kubectl --kubeconfig=/dev/null kustomize "${overlay_dir}"
  } > "${tmp_file}"

  if [[ -n ${PRETTIER:-} ]]; then
    read -r -a PRETTIER_CMD <<< "${PRETTIER}"
    "${PRETTIER_CMD[@]}" --write "${tmp_file}" > /dev/null
  elif [[ -x "${REPO_ROOT}/node_modules/.bin/prettier" ]]; then
    "${REPO_ROOT}/node_modules/.bin/prettier" --write "${tmp_file}" > /dev/null
  elif [[ -x "${REPO_ROOT}/.devcontainer/dependencies/node_modules/.bin/prettier" ]]; then
    "${REPO_ROOT}/.devcontainer/dependencies/node_modules/.bin/prettier" --write "${tmp_file}" > /dev/null
  elif [[ -x "${HOME}/.cache/gdc-solutions-ci/node_modules/.bin/prettier" ]]; then
    "${HOME}/.cache/gdc-solutions-ci/node_modules/.bin/prettier" --no-config --prose-wrap always --write "${tmp_file}" > /dev/null
  fi

  cp "${tmp_file}" "${output_file}"
  rm -f "${tmp_file}"
  echo "Rendered ${overlay_dir} to ${output_file}"
}

for v in "${VARIANTS[@]}"; do
  render_variant "${v}"
done
