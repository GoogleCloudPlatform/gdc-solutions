# Deterministically renders Kustomize overlays (base/ + overlays/<env>/) into
# Google Cloud Config Delivery FleetPackage hydration targets:
#   fleet-package/environments/{store-1,store-2,central-aggregator}/manifests.yaml

set -o errexit
set -o nounset
set -o pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SOLUTION_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
REPO_ROOT="$(git -C "${SCRIPT_DIR}" rev-parse --show-toplevel 2> /dev/null || (cd "${SOLUTION_ROOT}/../../.." && pwd))"

CHECK_ONLY="false"
for arg in "$@"; do
  case "${arg}" in
  --check)
    CHECK_ONLY="true"
    ;;
  -h | --help)
    echo "Usage: $0 [--check]"
    echo "  (default)  Render overlays/{store-1,store-2,central-aggregator} into fleet-package/environments/*/manifests.yaml"
    echo "  --check    Verify zero drift between overlays/* and fleet-package/environments/*/manifests.yaml without modifying files"
    exit 0
    ;;
  *)
    echo "[ERROR] Unknown argument: ${arg}" >&2
    exit 1
    ;;
  esac
done

if [[ ${CHECK_ONLY} == "false" ]]; then
  "${SOLUTION_ROOT}/fleet-package/render.sh"
fi

ENVIRONMENTS=("store-1" "store-2" "central-aggregator")
DRIFT_COUNT=0

for env in "${ENVIRONMENTS[@]}"; do
  overlay_dir="${SOLUTION_ROOT}/overlays/${env}"
  target_manifest="${SOLUTION_ROOT}/fleet-package/environments/${env}/manifests.yaml"

  if [[ ! -d ${overlay_dir} ]]; then
    echo "[FAIL] Missing Kustomize overlay directory: ${overlay_dir}" >&2
    exit 1
  fi

  rendered_tmp="$(mktemp --suffix=.yaml)"
  {
    cat << 'EOF'
# Copyright 2026 Google LLC
#
# Licensed under the Apache License, Version 2.0 (the "License");
# you may not use this file except in compliance with the License.
# You may obtain a copy of the License at
#
#     http://www.apache.org/licenses/LICENSE-2.0
#
# Unless required by applicable law or agreed to in writing, software
# distributed under the License is distributed on an "AS IS" BASIS,
# WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
# See the License for the specific language governing permissions and
# limitations under the License.

# Generated by render.sh from overlays/. Do not edit by hand.
EOF
    kubectl --kubeconfig=/dev/null kustomize "${overlay_dir}"
  } > "${rendered_tmp}"

  if [[ -n ${PRETTIER:-} ]]; then
    read -r -a PRETTIER_CMD <<< "${PRETTIER}"
    "${PRETTIER_CMD[@]}" --write "${rendered_tmp}" > /dev/null
  elif [[ -x "${REPO_ROOT}/node_modules/.bin/prettier" ]]; then
    "${REPO_ROOT}/node_modules/.bin/prettier" --write "${rendered_tmp}" > /dev/null
  elif [[ -x "${REPO_ROOT}/.devcontainer/dependencies/node_modules/.bin/prettier" ]]; then
    "${REPO_ROOT}/.devcontainer/dependencies/node_modules/.bin/prettier" --write "${rendered_tmp}" > /dev/null
  elif [[ -x "${HOME}/.cache/gdc-solutions-ci/node_modules/.bin/prettier" ]]; then
    "${HOME}/.cache/gdc-solutions-ci/node_modules/.bin/prettier" --no-config --prose-wrap always --write "${rendered_tmp}" > /dev/null
  fi

  if [[ ! -f ${target_manifest} ]]; then
    echo "[FAIL] [${env}] Target manifest missing: ${target_manifest}" >&2
    DRIFT_COUNT=$((DRIFT_COUNT + 1))
  elif ! diff -u "${rendered_tmp}" "${target_manifest}"; then
    echo "[FAIL] [${env}] Drift detected between overlays/${env} and fleet-package/environments/${env}/manifests.yaml" >&2
    DRIFT_COUNT=$((DRIFT_COUNT + 1))
  else
    sha_val="$(sha256sum "${target_manifest}" | awk '{print $1}')"
    line_count="$(wc -l < "${target_manifest}" | tr -d ' ')"
    echo "[PASS] [${env}] Zero drift verified (lines=${line_count}, sha256=${sha_val:0:16}...)"
  fi
  rm -f "${rendered_tmp}"
done

if [[ -d "${SOLUTION_ROOT}/clusters" ]]; then
  echo "[FAIL] Obsolete directory 'clusters/' still exists at ${SOLUTION_ROOT}/clusters" >&2
  DRIFT_COUNT=$((DRIFT_COUNT + 1))
fi
if [[ -d "${SOLUTION_ROOT}/data" ]]; then
  echo "[FAIL] Obsolete directory 'data/' still exists at ${SOLUTION_ROOT}/data" >&2
  DRIFT_COUNT=$((DRIFT_COUNT + 1))
fi

if [[ ${DRIFT_COUNT} -gt 0 ]]; then
  echo "[FAIL] FleetPackage manifest verification failed with ${DRIFT_COUNT} error(s)." >&2
  exit 1
fi

echo "[PASS] All 3 FleetPackage environments (store-1, store-2, central-aggregator) are 100% in sync with Kustomize overlays."
